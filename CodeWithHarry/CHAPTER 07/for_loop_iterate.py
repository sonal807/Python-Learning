#iterating the element of list using for loop
li = [1, 2, 3, 5, 8, 13]
for i in li:
    print(i)

#iterating the elements of tuple using for loop
tu = (11, 22, 33, 44, 55, 66)
for i in tu:
    print(i)

#iterating the elements of set using for loop
s = {1, 2, 4, 5}
for i in s:
    print(i)

#iterating the elements of string using for loop
str = "Sonalrai"
for i in str:
    print(i)