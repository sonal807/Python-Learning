friends = ["Apple", "Orange", 6, 345.06, False, "aaksh", "Rohan"]
print(friends)
print(friends[1])

friends[1] = "Mango" # unlike strings lists are mutable
print(friends)

#list can be indexed just as string starting from 0 to n-1

#list slicing (can be done just like in string)
print(friends[1:6])
print(friends[1:6:2])

