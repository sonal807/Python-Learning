a = "Sonal is a good boy \nBut not a bad boy" #\n is used to go to new line
print(a)

b = "Sonal is a good boy\tBut not a bad boy" #\t is used for white spaces
print(b)

c ="Sonal is a good boy \nBut not a bad \"boy\" " #\"\" is use to write a word in a string in double quotes
print(c)

d = "Sonal is a good boy \bBut not a bad boy" #\b erases the previous character
print(d)

e = "Sonal is a good boy\rBut not a bad boy" #\r moves cursor to line start
print(e)