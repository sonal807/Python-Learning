name = "Sonal"
print(len(name))#print the length of the string

nameshort = name[0:3] # start from indes 0 all the way till 3, excluding 3
print(nameshort)

character1 = name[1]
print(character1) # it will give the letter at index 1 as output

print(name[:4]) #it will give the letters from index 0 to 4 excluding 4 as output
print(name[1:]) #it will give the letters form index 0 to 4 as output

#negativeslicing
print(name[-4:-1]) #start from indes -4(1) all the way till -1(4), excluding -1

#skip slicing
word = "amazing"
print(word[1:6:2]) #it will give the letters from index 1 to 6 excluding 6 by skipping 1 steps




